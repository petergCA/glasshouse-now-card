// Builds test/icons.js (a small subset of Material Design Icons, Apache-2.0) for the harness.
// Usage: (in a scratch dir with @mdi/js installed)  node make-icons.cjs /path/to/test/icons.js
const mdi = require(require.resolve('@mdi/js', { paths: [process.cwd(), __dirname] }));
const names = `lock lock-open-variant lock-alert lightbulb lightbulb-outline lightbulb-group weather-pouring
window-open-variant window-closed-variant door-open door-closed garage-variant garage-open-variant
battery-alert-variant-outline lan-disconnect washing-machine tumble-dryer dishwasher printer-3d-nozzle
timer-outline progress-clock stove robot-vacuum ev-station coffee-maker home-import-outline home-export-outline
map-marker-outline motion-sensor motion-sensor-off water-alert water-check alert alert-circle-outline
lightbulb-on-outline check-circle-outline information-outline shield-off-outline shield-alert shield-lock shield-sync
toggle-switch-variant toggle-switch-variant-off fan fan-off play-circle-outline pause-circle-outline
window-shutter window-shutter-open square-rounded square-rounded-outline smoke-detector-alert
thermometer-alert water-percent-alert account home-outline`.split(/\s+/).filter(Boolean);
const out = {};
for (const n of names) {
  const key = 'mdi' + n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
  if (mdi[key]) out['mdi:' + n] = mdi[key];
  else console.error('missing', n);
}
require('fs').writeFileSync(process.argv[2],
  '// Generated by make-icons.cjs: a subset of Material Design Icons (Apache-2.0, pictogrammers.com).\n' +
  'window.GH_TEST_ICONS = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log('wrote', Object.keys(out).length, 'icons');
